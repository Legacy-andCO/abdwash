export const translations: Record<Language, Record<TranslationKey, string>> = {
  en,
  ar,
};

export function appLocale(language: Language): AppLocale {
  return language === "ar" ? "ar-AE" : "en-AE";
}

export function appDirection(language: Language): "rtl" | "ltr" {
  return language === "ar" ? "rtl" : "ltr";
}

export function translate(
  language: Language,
  key: TranslationKey,
  values: Record<string, string | number> = {},
): string {
  return Object.entries(values).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    translations[language][key] ?? translations.en[key],
  );
}

export function preferredLanguage(value?: string | null): Language {
  return value?.toLowerCase().startsWith("ar") ? "ar" : "en";
}

